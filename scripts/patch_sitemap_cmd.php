<?php
/**
 * Patch GenerateSitemapCommand::buildSitemapIndex() to deduplicate entries.
 */
$file = __DIR__ . '/../app/Console/Commands/GenerateSitemapCommand.php';
$src  = file_get_contents($file);

$newMethod = <<<'PHPCODE'
    protected function buildSitemapIndex(array $files): void
    {
        // Collect filenames already included via generated $files to avoid duplicates
        $generatedFilenames = array_filter(array_map(
            fn($f) => $f ? basename((string) $f) : null,
            $files
        ));

        // SitemapController-managed (dynamic) endpoints
        // — skip any whose filename is already covered by a generated static file
        $controllerEndpoints = array_values(array_filter([
            $this->baseUrl . '/sitemap-pages.xml',
            $this->baseUrl . '/sitemap-services.xml',
            $this->baseUrl . '/sitemap-cities.xml',
            $this->baseUrl . '/sitemap-districts.xml',
            $this->baseUrl . '/sitemap-blog.xml',
            $this->baseUrl . '/sitemap-gallery.xml',
            $this->baseUrl . '/sitemap-videos.xml',
            $this->baseUrl . '/sitemap-clusters.xml',
        ], fn($loc) => !in_array(basename($loc), $generatedFilenames, true)));

        $lines   = ['<?xml version="1.0" encoding="UTF-8"?>'];
        $lines[] = '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">';
        $lines[] = '  <!-- Static sitemaps: generated by php artisan sitemap:generate -->';

        // Generated static/pseo/article/cluster sitemaps
        foreach ($files as $filepath) {
            if (empty($filepath)) continue;
            $filename = basename((string) $filepath);
            $loc      = $this->baseUrl . '/' . $filename;
            $lines[]  = "  <sitemap>";
            $lines[]  = "    <loc>{$loc}</loc>";
            $lines[]  = "    <lastmod>{$this->now}</lastmod>";
            $lines[]  = "  </sitemap>";
        }

        $lines[] = '  <!-- Dynamic sitemaps: served live by SitemapController -->';

        // Controller-generated sitemaps (deduplicated)
        foreach ($controllerEndpoints as $loc) {
            $lines[] = "  <sitemap>";
            $lines[] = "    <loc>{$loc}</loc>";
            $lines[] = "    <lastmod>{$this->now}</lastmod>";
            $lines[] = "  </sitemap>";
        }

        $lines[] = '</sitemapindex>';
        $xml     = implode("\n", $lines);

        $total  = count($generatedFilenames) + count($controllerEndpoints);
        $target = public_path('sitemap-index.xml');
        File::put($target, $xml);
        $this->line("   ✓ sitemap-index.xml written to public/ ({$total} unique sub-sitemaps)");
    }
PHPCODE;

// Find the old method start and end
$start = strpos($src, '    protected function buildSitemapIndex(array $files): void');
if ($start === false) {
    echo "ERROR: Could not find buildSitemapIndex method\n";
    exit(1);
}

// Find the closing brace by counting braces
$depth = 0;
$i     = $start;
$len   = strlen($src);
$end   = $start;
$inMethod = false;
while ($i < $len) {
    if ($src[$i] === '{') {
        $depth++;
        $inMethod = true;
    } elseif ($src[$i] === '}') {
        $depth--;
        if ($inMethod && $depth === 0) {
            $end = $i + 1;
            break;
        }
    }
    $i++;
}

if ($end === $start) {
    echo "ERROR: Could not find closing brace\n";
    exit(1);
}

$oldMethod = substr($src, $start, $end - $start);
echo "OLD METHOD length: " . strlen($oldMethod) . " chars\n";
echo "First 80 chars: " . substr($oldMethod, 0, 80) . "\n";

$patched = str_replace($oldMethod, $newMethod, $src);

if ($patched === $src) {
    echo "ERROR: Replacement produced no change\n";
    exit(1);
}

file_put_contents($file, $patched);
echo "SUCCESS: buildSitemapIndex patched.\n";
echo "New method length: " . strlen($newMethod) . " chars\n";
