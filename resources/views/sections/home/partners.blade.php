{{-- Step-by-Step Paused Auto-Slide & Touch Swipe Script --}}
<script>
document.addEventListener('DOMContentLoaded', function () {
    const track = document.getElementById('mitra-carousel-track');
    const wrapper = document.getElementById('mitra-carousel-wrapper');
    const dotsContainer = document.getElementById('mitra-carousel-dots');
    
    if (!track || !wrapper) return;

    let items = Array.from(track.children);
    let totalItems = items.length;
    let currentIndex = 0;
    let intervalId = null;
    let isHovered = false;
    let isDragging = false;
    let startX = 0;
    let currentTranslate = 0;
    let prevTranslate = 0;

    function getItemWidth() {
        if (items.length === 0) return 280;
        const style = window.getComputedStyle(track);
        const gap = parseFloat(style.gap) || 16;
        return items[0].offsetWidth + gap;
    }

    function getVisibleCount() {
        const wrapperWidth = wrapper.offsetWidth;
        const itemWidth = getItemWidth();
        return Math.floor(wrapperWidth / itemWidth) || 1;
    }

    function getMaxIndex() {
        const visible = getVisibleCount();
        return Math.max(0, totalItems - visible);
    }

    function updateCarousel() {
        const itemWidth = getItemWidth();
        const maxIdx = getMaxIndex();
        
        if (currentIndex > maxIdx) {
            currentIndex = 0;
        } else if (currentIndex < 0) {
            currentIndex = maxIdx;
        }

        const translateX = -(currentIndex * itemWidth);
        track.style.transform = `translateX(${translateX}px)`;
        prevTranslate = translateX;

        // Update Dots
        if (dotsContainer) {
            const dots = Array.from(dotsContainer.children);
            dots.forEach((dot, idx) => {
                if (idx === currentIndex) {
                    dot.className = 'w-6 h-2 bg-emerald-400 rounded-full transition-all duration-300';
                } else {
                    dot.className = 'w-2 h-2 bg-white/30 hover:bg-white/60 rounded-full transition-all duration-300 cursor-pointer';
                }
            });
        }
    }

    function createDots() {
        if (!dotsContainer) return;
        dotsContainer.innerHTML = '';
        const maxIdx = getMaxIndex();
        
        for (let i = 0; i <= maxIdx; i++) {
            const dot = document.createElement('button');
            dot.setAttribute('aria-label', `Go to slide ${i + 1}`);
            dot.className = i === 0 ? 'w-6 h-2 bg-emerald-400 rounded-full transition-all duration-300' : 'w-2 h-2 bg-white/30 hover:bg-white/60 rounded-full transition-all duration-300 cursor-pointer';
            dot.addEventListener('click', () => {
                currentIndex = i;
                updateCarousel();
                restartInterval();
            });
            dotsContainer.appendChild(dot);
        }
    }

    function nextSlide() {
        const maxIdx = getMaxIndex();
        if (currentIndex >= maxIdx) {
            currentIndex = 0;
        } else {
            currentIndex++;
        }
        updateCarousel();
    }

    function startInterval() {
        stopInterval();
        // Paused Auto-Slide interval: 1.8 seconds delay per step
        intervalId = setInterval(() => {
            if (!isHovered && !isDragging) {
                nextSlide();
            }
        }, 1800);
    }

    function stopInterval() {
        if (intervalId) clearInterval(intervalId);
    }

    function restartInterval() {
        stopInterval();
        startInterval();
    }

    // Hover listeners to pause autoplay
    wrapper.addEventListener('mouseenter', () => { isHovered = true; });
    wrapper.addEventListener('mouseleave', () => { isHovered = false; });

    // Touch & Mouse Drag Handlers
    function touchStart(e) {
        isDragging = true;
        startX = e.type.includes('mouse') ? e.pageX : e.touches[0].clientX;
        track.style.transition = 'none';
        stopInterval();
    }

    function touchMove(e) {
        if (!isDragging) return;
        const currentX = e.type.includes('mouse') ? e.pageX : e.touches[0].clientX;
        const diff = currentX - startX;
        currentTranslate = prevTranslate + diff;
        track.style.transform = `translateX(${currentTranslate}px)`;
    }

    function touchEnd() {
        if (!isDragging) return;
        isDragging = false;
        track.style.transition = 'transform 0.7s ease-in-out';
        
        const movedBy = currentTranslate - prevTranslate;
        
        if (movedBy < -40) {
            currentIndex++;
        } else if (movedBy > 40) {
            currentIndex--;
        }
        
        updateCarousel();
        startInterval();
    }

    // Add Events
    track.addEventListener('touchstart', touchStart, { passive: true });
    track.addEventListener('touchmove', touchMove, { passive: true });
    track.addEventListener('touchend', touchEnd);

    track.addEventListener('mousedown', touchStart);
    track.addEventListener('mousemove', touchMove);
    track.addEventListener('mouseup', touchEnd);
    track.addEventListener('mouseleave', () => { if (isDragging) touchEnd(); });

    // Window Resize Handler
    window.addEventListener('resize', () => {
        createDots();
        updateCarousel();
    });

    // Init
    createDots();
    updateCarousel();
    startInterval();
});
</script>
